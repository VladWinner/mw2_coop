#!/usr/bin/env python3
"""Makes src/console_texts_gen.h (the built-in console texts) from content/release/localizedstrings/console.str.

  python -I tools/gen_console_texts.py            write the header
  python -I tools/gen_console_texts.py --check    fail if the header is out of date, or if src/console.c uses a text name
                                                  that console.str does not define (or console.str has a text nothing uses)

console.str is the one place the console's words are written; the game reads the same file from mw2coop/localizedstrings at start and
its texts replace the built-in ones (src/ctexts.c, loader in src/localize.c).
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
STR = os.path.join(HERE, "..", "content", "release", "localizedstrings", "console.str")
OUT = os.path.join(HERE, "..", "src", "console_texts_gen.h")
SRC = os.path.join(HERE, "..", "src", "console.c")
BS = chr(92)


def unquote(q):
    out, i = [], 0
    while i < len(q):
        c = q[i]
        if c == BS and i + 1 < len(q):
            i += 1
            out.append(chr(10) if q[i] == "n" else q[i])
        else:
            out.append(c)
        i += 1
    return "".join(out)


def parse():
    texts = []
    name = en = ru = None
    for line in open(STR, encoding="utf-8").read().splitlines():
        t = line.strip()
        if not t or t.startswith("//"):
            continue
        m = re.match(r'(REFERENCE|LANG_ENGLISH|LANG_RUSSIAN)\s+(.*)$', t)
        if not m:
            continue
        key, rest = m.groups()
        if key == "REFERENCE":
            if name:
                texts.append((name, en, ru))
            name, en, ru = rest.strip(), None, None
        else:
            q = re.match(r'"((?:[^"\\]|\\.)*)"', rest)
            if not q:
                raise SystemExit("bad line: " + line)
            val = unquote(q.group(1))
            if key == "LANG_ENGLISH":
                en = val
            else:
                ru = val
    if name:
        texts.append((name, en, ru))
    for n, e, r in texts:
        if e is None or r is None:
            raise SystemExit("text %s has no English or no Russian line" % n)
    return texts


def c_literal(text):
    return '"' + text.replace(BS, BS + BS).replace('"', BS + '"').replace(chr(10), BS + "n") + '"'


def build(texts):
    lines = ["// Generated by tools/gen_console_texts.py from content/release/localizedstrings/console.str: do not edit."]
    for n, e, r in texts:
        lines.append("\t{%s, %s, %s}," % (c_literal(n), c_literal(e), c_literal(r)))
    return (chr(13) + chr(10)).join(lines) + chr(13) + chr(10)


def main():
    texts = parse()
    text = build(texts)
    if "--check" in sys.argv:
        bad = 0
        for n, e, r in texts:  # the console fills %s / %d in the same order in both languages
            if re.findall(r"%[sd]", e) != re.findall(r"%[sd]", r):
                print("%s: the English and Russian texts have different %%s / %%d placeholders" % n)
                bad = 1
        have = open(OUT, encoding="utf-8", newline="").read() if os.path.exists(OUT) else ""
        if have != text:
            print("src/console_texts_gen.h is out of date: run python -I tools/gen_console_texts.py")
            bad = 1
        code = open(SRC, encoding="utf-8").read()
        used = set(re.findall(r'"(CON_[A-Z0-9_]+)"', code))
        defined = {n for n, _, _ in texts}
        for n in sorted(used - defined):
            print("console.c uses %s, which console.str does not define" % n)
            bad = 1
        for n in sorted(defined - used):
            print("console.str defines %s, which console.c does not use" % n)
            bad = 1
        if not bad:
            print("console texts: %d names, header and console.c agree" % len(texts))
        return bad
    with open(OUT, "w", encoding="utf-8", newline="") as f:
        f.write(text)
    print("wrote", os.path.normpath(OUT), len(texts), "texts")
    return 0


if __name__ == "__main__":
    sys.exit(main())
