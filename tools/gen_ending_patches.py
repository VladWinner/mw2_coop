"""Write the ending map (knife fight, museum credits) co-op patches, taking every replaced text
from the extracted game scripts so it matches byte for byte.
Usage: python -I gen_ending_patches.py <extracted gsc root> <mod content/patches/maps dir>"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gsc_patch import Patch  # noqa: E402

gsc_root, out_dir = sys.argv[1], sys.argv[2]
M = 'maps\\_mw2coop_ending::'

e = Patch(gsc_root, 'ending/maps/ending.gsc', out_dir)
e.note('''1. The map's mode: in co-op an unknown or empty ui_char_museum_mode means "credits_1" (from
   af_chase: knife fight, then credits).''')
e.subst('main', 'level.level_mode =  getdvar( "ui_char_museum_mode" );', 'level.level_mode = ' + M + 'museum_mode();')
e.write('ending.gsc.patch', '''
mw2coop patch for maps/ending.gsc (ending: knife fight and museum credits, Modern Warfare 2,
64-bit Steam build). Generated by tools/gen_ending_patches.py; do not edit by hand.
Co-op logic lives in mw2coop/scripts/maps/_mw2coop_ending.gsc.
''')
