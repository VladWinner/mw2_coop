#!/usr/bin/env python3
"""Makes src/dvar_descriptions_gen.h (dvar name and description pairs) from an unpacked 64-bit iw4sp.exe.

  python -I tools/gen_dvar_descriptions.py <iw4sp.exe dumped with realigned sections> [out]

The 64-bit dvar structure has no description field, but every Dvar_Register* call in the executable gets the description
as a string argument. This reads those call sites (the register functions' RVAs are below) and keeps name and description.
Needs capstone and pefile.
"""
import re
import struct
import sys

import capstone
import pefile
from capstone.x86 import X86_OP_MEM, X86_OP_REG, X86_REG_RIP, X86_REG_RSP

# register function RVA -> where the description is: a register name, or the caller's stack offset
REGISTER = {
    0x26c930: "r9",     # bool
    0x26cf20: "r9",     # string
    0x26cb10: 0x20,     # enum
    0x26cc10: 0x28,     # int
    0x26cb90: 0x28,     # float
    0x26d150: 0x30,     # vec2
    0x26d1e0: 0x38,     # vec3
    0x26d280: 0x30,     # color3
    0x26d310: 0x40,     # vec4
}


def main():
    path = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) > 2 else "src/dvar_descriptions_gen.h"
    data = open(path, "rb").read()
    pe = pefile.PE(path, fast_load=True)
    pe.parse_data_directories([pefile.DIRECTORY_ENTRY["IMAGE_DIRECTORY_ENTRY_EXCEPTION"]])
    text = next(s for s in pe.sections if s.Name.startswith(b".text"))
    rdata = next(s for s in pe.sections if s.Name.startswith(b".rdata"))
    r0, r1 = rdata.VirtualAddress, rdata.VirtualAddress + rdata.Misc_VirtualSize
    t0, t1 = text.VirtualAddress, text.VirtualAddress + text.Misc_VirtualSize

    def cstr(a):
        if not r0 <= a < r1:
            return None
        e = data.index(b"\0", a)
        s = data[a:e]
        if not s or len(s) > 400 or any(c < 32 and c not in (9, 10) for c in s):
            return None
        try:
            return s.decode("utf-8")
        except UnicodeDecodeError:
            return s.decode("latin-1")

    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_64)
    md.detail = True
    regname = md.reg_name
    result = {}
    for rf in pe.DIRECTORY_ENTRY_EXCEPTION:
        b, e = rf.struct.BeginAddress, rf.struct.EndAddress
        if not (t0 <= b < t1) or e - b > 0x20000:
            continue
        regs, slots = {}, {}
        for i in md.disasm(data[b:e], b):
            ops = i.operands
            if i.mnemonic == "lea" and len(ops) == 2 and ops[0].type == X86_OP_REG and ops[1].type == X86_OP_MEM \
                    and ops[1].mem.base == X86_REG_RIP:
                s = cstr(i.address + i.size + ops[1].mem.disp)
                r = regname(ops[0].reg)
                if s is not None:
                    regs[r] = s
                else:
                    regs.pop(r, None)
            elif i.mnemonic == "mov" and len(ops) == 2 and ops[0].type == X86_OP_MEM and ops[1].type == X86_OP_REG \
                    and ops[0].mem.base == X86_REG_RSP and ops[0].mem.index == 0:
                r = regname(ops[1].reg)
                if r in regs:
                    slots[ops[0].mem.disp] = regs[r]
                else:
                    slots.pop(ops[0].mem.disp, None)
            elif i.mnemonic == "mov" and len(ops) == 2 and ops[0].type == X86_OP_REG:
                regs.pop(regname(ops[0].reg), None)
            elif i.mnemonic == "call":
                if ops[0].type == 2 and ops[0].imm in REGISTER:
                    where = REGISTER[ops[0].imm]
                    name = regs.get("rcx")
                    desc = regs.get(where) if isinstance(where, str) else slots.get(where)
                    if name and desc and re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name) and name != desc:
                        result.setdefault(name, desc)
                for r in ("rax", "rcx", "rdx", "r8", "r9", "r10", "r11"):
                    regs.pop(r, None)
    emit(result, out)


def c_string(text):
    out = []
    for ch in text.encode("utf-8"):
        if ch in (34, 92):
            out.append("\\" + chr(ch))
        elif 32 <= ch < 127:
            out.append(chr(ch))
        else:
            out.append("\\%03o" % ch)
    return '"' + "".join(out) + '"'


def emit(result, out):
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("// generated by tools/gen_dvar_descriptions.py from the register calls of the 64-bit iw4sp.exe; sorted by name, case-insensitive\n")
        f.write("static const char *const dvar_description_table[][2] = {\n")
        for k in sorted(result, key=str.lower):
            f.write("\t{%s, %s},\n" % (c_string(k), c_string(" ".join(result[k].split()))))
        f.write("};\n")
    print("wrote", out, len(result), "descriptions")


if __name__ == "__main__":
    main()
