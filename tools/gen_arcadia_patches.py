"""Write the Exodus (arcadia) co-op patches, taking every replaced text from the extracted game
scripts so it matches byte for byte: the enemy changes (tools/seek_patch.py) and the laser
designator for one of the two players at random (maps\\_mw2coop_arcadia).
Usage: python -I gen_arcadia_patches.py <extracted gsc root> <mod content/patches/maps dir>"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gsc_patch import Patch  # noqa: E402
from seek_patch import enemies_for_both  # noqa: E402

gsc_root, out_dir = sys.argv[1], sys.argv[2]
LASER = 'maps\\_mw2coop_arcadia::laser_player()'

# ---------------------------------------------------------------- arcadia.gsc
p = Patch(gsc_root, 'arcadia/maps/arcadia.gsc', out_dir)
p.note('''1. The laser designator (the Stryker's targets, the golf course artillery) goes to one player,
   either of the two at random (maps\\_mw2coop_arcadia::laser_player; player 1 outside co-op).''')
p.replace('\tthread laser_targeting_device( level.player );\n', '\tthread laser_targeting_device( ' + LASER + ' );\n')
p.write('arcadia.gsc.patch', '''
mw2coop patch for maps/arcadia.gsc (Exodus, Modern Warfare 2, 64-bit Steam build). Generated by
tools/gen_arcadia_patches.py; do not edit by hand.''')

# ---------------------------------------------------------------- arcadia_code.gsc
p = Patch(gsc_root, 'arcadia/maps/arcadia_code.gsc', out_dir)
n = enemies_for_both(p, [])
p.note('''{0}. The laser hints show to the player who has the designator.'''.format(n + 1))
p.subst('laser_hint_print', 'thread display_hint( "use_laser" );', LASER + ' thread display_hint( "use_laser" );')
p.subst('laser_golf_hint_print', 'thread display_hint( "use_laser_golf" );',
        LASER + ' thread display_hint( "use_laser_golf" );')
p.write('arcadia_code.gsc.patch', '''
mw2coop patch for maps/arcadia_code.gsc (Exodus, Modern Warfare 2, 64-bit Steam build). Generated by
tools/gen_arcadia_patches.py; do not edit by hand.''')
