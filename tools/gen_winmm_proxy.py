"""Generate the winmm.dll proxy export stubs from the system winmm.dll export table.
Writes src/winmm_stubs.S (one jmp per export through winmm_real[]), src/winmm.def and
src/winmm_names.h. Usage: python -I tools/gen_winmm_proxy.py [path-to-system-winmm.dll]"""
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
# Exports implemented in C (src/hooks.c) instead of a plain jmp stub.
HOOKED = {'timeGetTime'}
SRC = os.path.join(HERE, '..', 'src')


def exports(path):
    d = open(path, 'rb').read()
    pe = struct.unpack_from('<I', d, 0x3c)[0]
    opt = pe + 24
    magic = struct.unpack_from('<H', d, opt)[0]
    assert magic in (0x10b, 0x20b), 'not a PE file'
    nsec = struct.unpack_from('<H', d, pe + 6)[0]
    optsz = struct.unpack_from('<H', d, pe + 20)[0]
    er = struct.unpack_from('<I', d, opt + (96 if magic == 0x10b else 112))[0]
    secs = [struct.unpack_from('<IIII', d, opt + optsz + 40 * i + 8) for i in range(nsec)]

    def r2o(r):
        for vsz, va, rsz, rp in secs:
            if va <= r < va + max(vsz, rsz):
                return r - va + rp
        raise ValueError(hex(r))

    o = r2o(er)
    _, _, nnam, _, an, _ = struct.unpack_from('<IIIIII', d, o + 16)
    out = []
    for i in range(nnam):
        no = r2o(struct.unpack_from('<I', d, r2o(an) + 4 * i)[0])
        out.append(d[no:d.index(b'\0', no)].decode())
    return out, magic == 0x10b


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.environ['SystemRoot'], 'System32', 'winmm.dll')
    names, x86 = exports(path)
    # the 32-bit proxy has files of its own (src/x86/): the 64-bit ones stay as they were
    out = os.path.join(SRC, 'x86') if x86 else SRC
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, 'winmm_stubs.S'), 'w', newline='\n') as f:
        f.write('# generated by tools/gen_winmm_proxy.py, do not edit\n\t.text\n')
        for i, n in enumerate(names):
            if n in HOOKED:
                continue
            if x86:
                # C symbols carry a leading underscore on 32-bit Windows; the stub keeps the caller's stack as it is
                f.write(f'\t.globl _{n}\n\t.p2align 4\n_{n}:\n\tjmp *_winmm_real+{4 * i}\n')
            else:
                f.write(f'\t.globl {n}\n\t.p2align 4\n{n}:\n\tjmpq *winmm_real+{8 * i}(%rip)\n')
    with open(os.path.join(out, 'winmm.def'), 'w', newline='\n') as f:
        f.write('LIBRARY winmm.dll\nEXPORTS\n')
        for n in names:
            f.write(f'\t{n}\n')
    with open(os.path.join(out, 'winmm_names.h'), 'w', newline='\n') as f:
        f.write('/* generated by tools/gen_winmm_proxy.py, do not edit */\n')
        f.write(f'#define WINMM_EXPORT_COUNT {len(names)}\n')
        for n in sorted(HOOKED):
            f.write(f'#define WINMM_IDX_{n} {names.index(n)}\n')
        f.write('static const char *const winmm_names[WINMM_EXPORT_COUNT] = {\n')
        for n in names:
            f.write(f'\t"{n}",\n')
        f.write('};\n')
    print('wrote', out, len(names), 'exports', '(32-bit)' if x86 else '(64-bit)')


if __name__ == '__main__':
    main()
