#!/usr/bin/env python3
"""Makes src/missions_gen.h (the mod's built-in mission rows) from content/release/missions.csv.

  python -I tools/gen_missions.py            write the header
  python -I tools/gen_missions.py --check    fail if the header is not what the csv gives

The csv is the one place the missions are listed: the game reads mw2coop/missions.csv at start and
its rows replace the built-in ones of the same map (src/missions.c).
"""
import csv
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CSV = os.path.join(HERE, "..", "content", "release", "missions.csv")
OUT = os.path.join(HERE, "..", "src", "missions_gen.h")
COLUMNS = ["map", "title", "zone", "zone_own", "picture"]


def build():
    rows = []
    with open(CSV, encoding="utf-8", newline="") as f:
        lines = [l for l in f.read().splitlines() if l.strip() and not l.startswith("//")]
    reader = csv.reader(lines)
    head = next(reader)
    if head != COLUMNS:
        raise SystemExit("missions.csv header is %r, expected %r" % (head, COLUMNS))
    for r in reader:
        if len(r) != len(COLUMNS):
            raise SystemExit("bad row %r" % (r,))
        rows.append(r)
    out = ["// Generated by tools/gen_missions.py from content/release/missions.csv: do not edit.", ""]
    for map_, title, zone, own, pic in rows:
        for text in (map_, title, zone):
            if '"' in text or chr(92) in text:
                raise SystemExit("quote or backslash in %r" % text)
        out.append('\t{"%s", "%s", "%s", %d, %d},' % (map_, title, zone, int(own), int(pic)))
    return (chr(13) + chr(10)).join(out) + chr(13) + chr(10)


def main():
    text = build()
    if "--check" in sys.argv:
        have = open(OUT, encoding="utf-8", newline="").read() if os.path.exists(OUT) else ""
        if have != text:
            print("src/missions_gen.h is out of date: run python -I tools/gen_missions.py")
            return 1
        print("missions_gen.h matches missions.csv")
        return 0
    with open(OUT, "w", encoding="utf-8", newline="") as f:
        f.write(text)
    print("wrote", os.path.normpath(OUT), text.count(chr(10)) - 2, "rows")
    return 0


if __name__ == "__main__":
    sys.exit(main())
