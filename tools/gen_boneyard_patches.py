"""Write the The Enemy of My Enemy (boneyard) UAZ ride patch, taking every replaced text from the
extracted game script so it matches byte for byte (maps\\_mw2coop_boneyard; boneyard.gsc keeps
its enemy patch from tools/gen_seek_patches.py).
Usage: python -I gen_boneyard_patches.py <extracted gsc root> <mod content/patches/maps dir>"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gsc_patch import Patch  # noqa: E402

gsc_root, out_dir = sys.argv[1], sys.argv[2]
M = 'maps\\_mw2coop_boneyard::'

p = Patch(gsc_root, 'boneyard/maps/boneyard_code.gsc', out_dir)
p.note('''1. The UAZ ride: when player 1 gets in, player 2 rides on the back seat with his own weapon,
   invulnerable while getting in as player 1 is, and into the C-130 with the UAZ.''')
p.subst('uaz_control', 'level.player EnableInvulnerability();',
        'level.player EnableInvulnerability();\n\tself ' + M + 'partner_boards();')
p.subst('uaz_control', 'level.player DisableInvulnerability();',
        'level.player DisableInvulnerability();\n\t' + M + 'partner_mounted();')
p.subst('park_uaz', 'self.dummy = dummy;', 'self.dummy = dummy;\n\t' + M + 'partner_seat_to( dummy );')
p.write('boneyard_code.gsc.patch', '''
mw2coop patch for maps/boneyard_code.gsc (The Enemy of My Enemy, Modern Warfare 2, 64-bit Steam build). Generated by
tools/gen_boneyard_patches.py; do not edit by hand.''')
