"""Write the Endgame boat chase (af_chase) co-op patches for the chase scripts (the same files
in the af_chase and ending zones), taking every replaced text from the extracted scripts so it
matches byte for byte. Every level.player of the chase becomes level.mw2coop_lead: the driver,
whoever mounted the boat first (player 1 outside co-op and until then).
Usage: python -I gen_boat_patches.py <extracted gsc root> <mod content/patches/maps dir>"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gsc_patch import Patch, func  # noqa: E402
import check_patches  # noqa: E402

gsc_root, out_dir = sys.argv[1], sys.argv[2]
M = 'maps\\_mw2coop_boat::'
LEAD = 'level.mw2coop_lead'


def functions_using_player(src):
    names = []
    for m in re.finditer(r'\n([A-Za-z_][A-Za-z0-9_]*)\([^\n]*\)[ \t]*\n\{', src):
        name = m.group(1)
        # a header inside a /* */ comment is no function
        if name in names or not check_patches.find_function(src, name):
            continue
        if re.search(r'level\.player(?![A-Za-z0-9_])', func(src, name)):
            names.append(name)
    return names


def lead_everywhere(p):
    for fn in functions_using_player(p.src):
        p.subst(fn, 'level.player', LEAD)


HEADER = '''
mw2coop patch for maps/{0} (Endgame boat chase; the same script in the af_chase and ending
zones; Modern Warfare 2, 64-bit Steam build). Generated by tools/gen_boat_patches.py; do not
edit by hand. Co-op logic lives in mw2coop/scripts/maps/_mw2coop_boat.gsc. Outside a co-op
campaign session level.mw2coop_lead is level.player and every change does what the original did.
'''

# ---------------------------------------------------------------- af_chase_code.gsc
c = Patch(gsc_root, 'af_chase/maps/af_chase_code.gsc', out_dir)
c.note('''1. Boarding: the player who sets off the jetty trigger drives; once he is on the boat the
   other player takes the seat across from Price as a gunner.''')
c.subst('trigger_boat_mount', 'self waittill( "trigger" );',
        'self waittill( "trigger", mw2coop_who );\n\t' + M + 'boat_mount( mw2coop_who );')
c.subst('setup_boat_for_drive', 'flag_set( "player_on_boat" );', 'flag_set( "player_on_boat" );\n\t' + M + 'boat_boarded();')
c.note('''2. Death in the boat: nobody can revive anyone there, so either player going down is the
   single player death (the boat flips, the mission fails); the passenger rolls with it.''')
c.subst('flip_when_player_dies', 'level.player waittill( "death" );', M + 'boat_rider_down();')
c.subst('flip_when_player_dies', 'level.player PlayerSetGroundReferenceEnt( offset_obj );',
        'level.player PlayerSetGroundReferenceEnt( offset_obj );\n\t' + M + 'boat_flip_partner( offset_obj );')
c.subst('flip_when_player_dies', '\t\tlastorg = linkobj.origin;\n\t\twait .05;\n\t}\n',
        '\t\tlastorg = linkobj.origin;\n\t\twait .05;\n\t}\n\t' + M + 'boat_flip_done();\n')
c.note('''3. Price keeps his tube: two gunners cover a side each (owner, 2026-10-21: no turning over),
   so the level's position triggers and the rapids' automatic turning leave him in his "left"
   pose, the one the level gives him by default, and the passenger lies across from him.''')
c.subst('price_position_switch', 'level.price.scripted_boat_pose = self.script_noteworthy;',
        'if ( !' + M + 'price_keeps_tube() )\n\t\tlevel.price.scripted_boat_pose = self.script_noteworthy;')
c.subst('set_price_auto_switch_pose', 'level.price.scripted_boat_pose = undefined;',
        'if ( ' + M + 'price_keeps_tube() )\n\t\treturn;\n\tlevel.price.scripted_boat_pose = undefined;')
c.note('''4. Everything else of the chase plays on the driver.''')
lead_everywhere(c)
c.write('af_chase_code.gsc.patch', HEADER.format('af_chase_code.gsc'))

# ---------------------------------------------------------------- af_chase_waterfall.gsc
w = Patch(gsc_root, 'af_chase/maps/af_chase_waterfall.gsc', out_dir)
w.note('''1. Over the waterfall: the passenger stops shooting, sinks beside the driver, and the fade
   to the next mission is on both screens.''')
w.subst('water_fall_edge', 'level.player DisableWeapons();', 'level.player DisableWeapons();\n\t' + M + 'passenger_over_edge();')
w.subst('water_fall_edge', 'level.player PlayerLinkTodelta( level.player_linkent, "tag_player", 1,0,0,0,0 );',
        'level.player PlayerLinkTodelta( level.player_linkent, "tag_player", 1,0,0,0,0 );\n\t' + M + 'passenger_underwater( level.player_linkent );')
w.subst('water_fall_edge', 'create_client_overlay( "black", 0, level.player )', 'create_client_overlay( "black", 0 )')
w.note('''2. Everything else of the chase plays on the driver.''')
lead_everywhere(w)
w.write('af_chase_waterfall.gsc.patch', HEADER.format('af_chase_waterfall.gsc'))

# ---------------------------------------------------------------- the driver everywhere else
for name in ('af_chase.gsc', 'af_chase_zodiac.gsc', '_vehicle_spline_zodiac.gsc', '_zodiac_drive.gsc'):
    p = Patch(gsc_root, 'af_chase/maps/' + name, out_dir)
    p.note('''1. The chase plays on the driver.''')
    lead_everywhere(p)
    p.write(name + '.patch', HEADER.format(name))
