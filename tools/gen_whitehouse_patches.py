"""Write the Whiskey Hotel (dc_whitehouse) co-op patches, taking every replaced text from the
extracted game scripts so it matches byte for byte: the enemy changes (tools/seek_patch.py) and a
flare for each player on the roof (COD-MOD gave player 2 one too).
Usage: python -I gen_whitehouse_patches.py <extracted gsc root> <mod content/patches/maps dir>"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gsc_patch import Patch  # noqa: E402
from seek_patch import enemies_for_both  # noqa: E402

gsc_root, out_dir = sys.argv[1], sys.argv[2]

# ---------------------------------------------------------------- dc_whitehouse.gsc
p = Patch(gsc_root, 'dc_whitehouse/maps/dc_whitehouse.gsc', out_dir)
n = enemies_for_both(p, ['whitehouse_main'])
p.note('''{0}. On the roof ("Use your flares!") player 2 gets a flare of his own too, as player 1 does
   (maps\\_mw2coop_whitehouse::partner_flare runs whitehouse_player_flare on player 2, with the
   weapon sync on "own" for the scene; flare_weapon in dc_whitehouse_code.gsc works on the player
   it runs on). Either player's flare stops the hint; the jets turn away with Foley's scene, as
   before.'''.format(n + 1))
p.replace('\tlevel.player thread whitehouse_player_flare();\n',
          '\tlevel.player thread whitehouse_player_flare();\n'
          '\tlevel thread maps\\_mw2coop_whitehouse::partner_flare( ::whitehouse_player_flare );\n')
p.write('dc_whitehouse.gsc.patch', '''
mw2coop patch for maps/dc_whitehouse.gsc (Whiskey Hotel, Modern Warfare 2, 64-bit Steam build).
Generated by tools/gen_whitehouse_patches.py; do not edit by hand.''')

# ---------------------------------------------------------------- dc_whitehouse_code.gsc
p = Patch(gsc_root, 'dc_whitehouse/maps/dc_whitehouse_code.gsc', out_dir)
p.note('''1. The flare goes to the player the function runs on (self) instead of level.player, so each
   player pops his own (player 1 alone outside co-op, as before).''')
p.subst('flare_weapon', 'level.player', 'self')
p.write('dc_whitehouse_code.gsc.patch', '''
mw2coop patch for maps/dc_whitehouse_code.gsc (Whiskey Hotel, Modern Warfare 2, 64-bit Steam
build). Generated by tools/gen_whitehouse_patches.py; do not edit by hand.''')
