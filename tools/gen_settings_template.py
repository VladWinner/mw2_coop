#!/usr/bin/env python3
"""Makes src/settings_template_gen.h (the built-in copy of content/release/settings.ini, as a C string) for src/settings.c.

  python -I tools/gen_settings_template.py            write the header
  python -I tools/gen_settings_template.py --check    fail if the header is not what the file gives

content/release/settings.ini is the one place the documented settings are written down. The game creates mw2coop\\settings.ini from it at start and brings an
existing one up to date without touching the values the player changed (src/inimerge.c).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "content", "release", "settings.ini")
OUT = os.path.join(HERE, "..", "src", "settings_template_gen.h")
NL = chr(10)
BS = chr(92)


def build():
    text = open(SRC, encoding="utf-8", newline="").read().replace(chr(13) + NL, NL)
    if "[" not in text or "=" not in text:
        raise SystemExit("settings.ini: no sections or keys")
    out = ["// Generated by tools/gen_settings_template.py from content/release/settings.ini: do not edit.", "static const char settings_template[] ="]
    for line in text.rstrip(NL).split(NL):
        out.append('\t"' + line.replace(BS, BS + BS).replace('"', BS + '"') + BS + 'n"')
    out[-1] += ";"
    return (chr(13) + NL).join(out) + chr(13) + NL


def main():
    text = build()
    if "--check" in sys.argv:
        have = open(OUT, encoding="utf-8", newline="").read() if os.path.exists(OUT) else ""
        if have != text:
            print("src/settings_template_gen.h is out of date: run python -I tools/gen_settings_template.py")
            return 1
        print("settings_template_gen.h matches settings.ini")
        return 0
    with open(OUT, "w", encoding="utf-8", newline="") as f:
        f.write(text)
    print("wrote", os.path.normpath(OUT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
