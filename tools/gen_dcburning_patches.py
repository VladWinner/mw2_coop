"""Write the Of Their Own Accord (dcburning) co-op patch, taking every replaced text from the
extracted game script so it matches byte for byte: the enemy changes (tools/seek_patch.py) and
the Black Hawk ride for two players (maps\\_mw2coop_dcburning).
Usage: python -I gen_dcburning_patches.py <extracted gsc root> <mod content/patches/maps dir>"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gsc_patch import Patch  # noqa: E402
from seek_patch import enemies_for_both  # noqa: E402

gsc_root, out_dir = sys.argv[1], sys.argv[2]
M = 'maps\\_mw2coop_dcburning::'

p = Patch(gsc_root, 'dcburning/maps/dcburning.gsc', out_dir)
n = enemies_for_both(p, ['AAA_sequence_bunker_to_commerce', 'AAA_sequence_heli_ride', 'ignoreme_on_squad_and_player',
                         'ignoreme_off_squad_and_player'])
p.note('''{0}. The Black Hawk ride: player 2 rides in the cabin behind the minigun, out of the same door, with
   his own weapon, invulnerable as player 1 is; at the missile hit he holds on as player 1 does, and
   lets go when the wreck is removed (the crash site takes both over).'''.format(n + 1))
p.subst('AAA_sequence_heli_ride', 'flag_set( "player_getting_on_minigun" );',
        'flag_set( "player_getting_on_minigun" );\n\t' + M + 'partner_boards();')
p.subst('start_heli_ride2', 'level.blackhawk.minigunUser = level.player;',
        'level.blackhawk.minigunUser = level.player;\n\t' + M + 'partner_boards();')
p.subst('AAA_sequence_heli_ride2', 'level.player playerlinkToDelta( level.blackhawk, "tag_player", 1, 20, 20, 10, 10 );',
        'level.player playerlinkToDelta( level.blackhawk, "tag_player", 1, 20, 20, 10, 10 );\n\t' + M + 'partner_holds_on();')
p.subst('AAA_sequence_heli_ride2', 'level.blackhawk vehicle_delete();',
        M + 'partner_lets_go();\n\tlevel.blackhawk vehicle_delete();')
p.write('dcburning.gsc.patch', '''
mw2coop patch for maps/dcburning.gsc (Of Their Own Accord, Modern Warfare 2, 64-bit Steam build). Generated by
tools/gen_dcburning_patches.py; do not edit by hand.''')
