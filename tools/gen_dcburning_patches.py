"""Write the Of Their Own Accord (dcburning) co-op patches (dcburning.gsc, _barrett.gsc), taking every replaced text from the
extracted game script so it matches byte for byte: the enemy changes (tools/seek_patch.py) and
the Black Hawk ride for two players (maps\\_mw2coop_dcburning).
Usage: python -I gen_dcburning_patches.py <extracted gsc root> <mod content/patches/maps dir>"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gsc_patch import Patch  # noqa: E402
from seek_patch import enemies_for_both  # noqa: E402

gsc_root, out_dir = sys.argv[1], sys.argv[2]
M = 'maps\\_mw2coop_dcburning::'

p = Patch(gsc_root, 'dcburning/maps/dcburning.gsc', out_dir)
n = enemies_for_both(p, ['AAA_sequence_bunker_to_commerce', 'AAA_sequence_heli_ride', 'ignoreme_on_squad_and_player',
                         'ignoreme_off_squad_and_player'])
p.note('''{0}. The Black Hawk ride: player 2 rides in the cabin behind the minigun, out of the same door, with
   his own weapon, invulnerable as player 1 is; at the missile hit he holds on as player 1 does, and
   lets go when the wreck is removed (the crash site takes both over).'''.format(n + 1))
p.subst('AAA_sequence_heli_ride', 'flag_set( "player_getting_on_minigun" );',
        'flag_set( "player_getting_on_minigun" );\n\t' + M + 'partner_boards();')
p.subst('start_heli_ride2', 'level.blackhawk.minigunUser = level.player;',
        'level.blackhawk.minigunUser = level.player;\n\t' + M + 'partner_boards();')
p.subst('AAA_sequence_heli_ride2', 'level.player playerlinkToDelta( level.blackhawk, "tag_player", 1, 20, 20, 10, 10 );',
        'level.player playerlinkToDelta( level.blackhawk, "tag_player", 1, 20, 20, 10, 10 );\n\t' + M + 'partner_holds_on();')
p.subst('AAA_sequence_heli_ride2', 'level.blackhawk vehicle_delete();',
        M + 'partner_lets_go();\n\tlevel.blackhawk vehicle_delete();')
p.note('''{0}. The Barrett on the Crow's Nest (maps\\_barrett, _barrett.gsc.patch): the enemies' warning shots at the player on the rifle
   (player_barrett_damage) hit whoever is on it, not always player 1.'''.format(n + 2))
p.subst('player_barrett_damage', 'level.player', 'mw2coop_user')
p.note('''{0}. The Javelin hints (pick it up, switch to it, fire; shown to both players) go away by the Javelin of the player who sees
   them: player_has_javelin() and javelin_equipped() asked player 1 also when a hint's break test asked them for player 2.'''.format(n + 3))
for fn in ('player_has_javelin', 'javelin_equipped'):
    p.subst(fn, 'level.player', 'mw2coop_player')
    p.subst(fn, fn + '()\n{\n', fn + '()\n{\n\tmw2coop_player = get_player_from_self();\n')
p.subst('should_break_javelin_pickup_hint', 'level.player', 'self')
p.subst('player_barrett_damage', 'while ( flag( "player_is_on_turret" ) )\n\t{\n',
        'while ( flag( "player_is_on_turret" ) )\n\t{\n\t\tmw2coop_user = ' + M + 'barrett_user();\n')
p.write('dcburning.gsc.patch', '''
mw2coop patch for maps/dcburning.gsc (Of Their Own Accord, Modern Warfare 2, 64-bit Steam build). Generated by
tools/gen_dcburning_patches.py; do not edit by hand.''')

# ---------------------------------------------------------------- _barrett.gsc (night audit 2026-11-17)
b = Patch(gsc_root, 'dcburning/maps/_barrett.gsc', out_dir)
b.note('''1. The Barrett on the Crow's Nest is for the player who uses it: the use trigger answered either player but put player 1 on the
   rifle wherever he stood; now the user gets on it, gets its hint, zoom lesson, recoil shock and HUD changes, and gets off where he
   got on (maps\\_mw2coop_dcburning::barrett_user()). Player 1's weapons and night-vision slot go to player 2 too (src/mirror.c):
   while player 1 is on the rifle, player 2 keeps his (barrett_partner_kit).''')
U = 'mw2coop_user'
b.subst('exchange_barrett_trigger', 'level.player', U)
b.subst('exchange_barrett_trigger', 'barrett_trigger waittill( "trigger" );',
        'barrett_trigger waittill( "trigger", ' + U + ' );\n\t\t' + U + ' = ' + M + 'barrett_got_on( ' + U + ' );')
b.subst('exchange_barrett_trigger', 'NightVisionForceOff();\n\t\t}\n',
        'NightVisionForceOff();\n\t\t}\n\t\t' + M + 'barrett_partner_kit( ' + U + ' );\n')
b.subst('exchange_barrett_trigger', 'flag_clear( "player_is_on_turret" );', 'flag_clear( "player_is_on_turret" );\n\t\t' + M + 'barrett_got_off();')
b.subst('exchange_trace_converter', 'level.player attackbuttonpressed()', M + 'barrett_attack_pressed()')
b.subst('exchange_player_fires', 'level.player shellshock( "barrett", 1.3 );',
        U + ' = ' + M + 'barrett_user();\n\t' + U + ' shellshock( "barrett", 1.3 );')
b.subst('player_learns_to_zoom', 'level.player GetNormalizedMovement()', M + 'barrett_movement()')
b.write('_barrett.gsc.patch', '''
mw2coop patch for maps/_barrett.gsc (Of Their Own Accord's Barrett, Modern Warfare 2, 64-bit Steam build). Generated by
tools/gen_dcburning_patches.py; do not edit by hand.''')
