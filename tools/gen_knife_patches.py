"""Write the knife fight (end of Endgame) co-op patches for maps/af_chase_knife_fight.gsc and
maps/af_chase_knife_fight_code.gsc (the same files in the af_chase and ending zones), taking
every replaced text from the extracted scripts so it matches byte for byte. Every level.player
of the scene becomes level.mw2coop_lead: the player who strikes Shepherd first (player 1
outside co-op and until then).
Usage: python -I gen_knife_patches.py <extracted gsc root> <mod content/patches/maps dir>"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gsc_patch import Patch, func  # noqa: E402

gsc_root, out_dir = sys.argv[1], sys.argv[2]
M = 'maps\\_mw2coop_knife::'
LEAD = 'level.mw2coop_lead'


def functions_using_player(src):
    names = []
    for m in re.finditer(r'\n([A-Za-z_][A-Za-z0-9_]*)\([^\n]*\)[ \t]*\n\{', src):
        name = m.group(1)
        if re.search(r'level\.player(?![A-Za-z0-9_])', func(src, name)):
            names.append(name)
    return names


def lead_everywhere(p):
    for fn in functions_using_player(p.src):
        p.subst(fn, 'level.player', LEAD)


# ---------------------------------------------------------------- af_chase_knife_fight_code.gsc
c = Patch(gsc_root, 'ending/maps/af_chase_knife_fight_code.gsc', out_dir)
c.note('''1. Input: the crawl to the revolver read this PC's mouse buttons (the other lockstep machine
   sees different input); in co-op the lead's usercmd, as the hints show (right +attack, left
   +speed_throw). The knife pull's Use button goes through the same helper (QA can hold it).''')
c.subst('hint_crawl_right', 'return level.player buttonpressed( "mouse2" );', 'return ' + M + 'crawl_pressed( "right", "mouse2" );')
c.subst('hint_crawl_left', 'return level.player buttonpressed( "mouse1" );', 'return ' + M + 'crawl_pressed( "left", "mouse1" );')
c.subst('use_pressed', 'return level.player UseButtonPressed();', 'return ' + M + 'use_pressed();')
c.subst('wait_for_player_to_start_pulling_knife', 'level.player UseButtonPressed()', M + 'use_pressed()')
c.note('''2. Who strikes Shepherd: the nearer player at each check; a melee by either player counts.''')
c.subst('wait_for_player_to_melee_shepherd', 'dist_to_shepherd = Distance( level.player.origin, level.shepherd.origin );',
        M + 'choose_lead();\n\t\tdist_to_shepherd = Distance( level.player.origin, level.shepherd.origin );')
c.subst('track_melee', 'level.player IsMeleeing()', M + 'any_meleeing()')
c.note('''3. The scene's fades on both screens in co-op.''')
c.subst('get_black_overlay', 'create_client_overlay( "black", 0, level.player )', M + 'black_overlay()')
c.note('''4. Everything else of the scene plays on the lead.''')
lead_everywhere(c)
c.write('af_chase_knife_fight_code.gsc.patch', '''
mw2coop patch for maps/af_chase_knife_fight_code.gsc (Endgame knife fight; the same script in the
af_chase and ending zones; Modern Warfare 2, 64-bit Steam build). Generated by
tools/gen_knife_patches.py; do not edit by hand. Co-op logic lives in
mw2coop/scripts/maps/_mw2coop_knife.gsc. Outside a co-op campaign session level.mw2coop_lead is
level.player and every change does what the original did.
''')

# ---------------------------------------------------------------- af_chase_knife_fight.gsc
k = Patch(gsc_root, 'ending/maps/af_chase_knife_fight.gsc', out_dir)
k.note('''1. Wake-up: player 2 wakes up beside player 1 with his own rig.''')
k.subst('wakeup_after_crash', 'level.player PlayerLinkToDelta( player_rig, "tag_player", 1, 0, 0, 0, 0, true );',
        'level.player PlayerLinkToDelta( player_rig, "tag_player", 1, 0, 0, 0, 0, true );\n\t' + M + 'partner_wakeup( anim_node, scene );')
k.note('''2. The player who strikes Shepherd plays the scene; the other goes down and watches, and gets
   up when Nikolai's helicopter comes.''')
k.subst('fight_turnbuckle', 'wait_for_player_to_melee_shepherd();', 'wait_for_player_to_melee_shepherd();\n\t' + M + 'lead_decided();')
k.subst('walkoff', 'spawn_nikolai();', 'spawn_nikolai();\n\t' + M + 'witness_gets_up();')
k.note('''3. The other player passes out when the lead strikes (lead_decided), comes to for the knife in
   Shepherd's eye and passes out again before the end.''')
k.subst('knife_kill', 'level notify ( "knife_pulled_out" );', 'level notify ( "knife_pulled_out" );\n\t' + M + 'witness_wakes();')
k.note('''4. Everything else of the scene plays on the lead.''')
lead_everywhere(k)
k.write('af_chase_knife_fight.gsc.patch', '''
mw2coop patch for maps/af_chase_knife_fight.gsc (Endgame knife fight; the same script in the
af_chase and ending zones; Modern Warfare 2, 64-bit Steam build). Generated by
tools/gen_knife_patches.py; do not edit by hand. Co-op logic lives in
mw2coop/scripts/maps/_mw2coop_knife.gsc. Outside a co-op campaign session level.mw2coop_lead is
level.player and every change does what the original did.
''')
