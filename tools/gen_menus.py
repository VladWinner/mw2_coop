#!/usr/bin/env python3
"""Makes src/menus_gen.h (the built-in copy of content/release/menus.menu, as a C string) for src/menutable.c.

  python -I tools/gen_menus.py            write the header
  python -I tools/gen_menus.py --check    fail if the header is not what the menu file gives

menus.menu is the one place the menus the mod adds are listed (Call of Duty .menu syntax); the game reads mw2coop/menus.menu at start and its
items replace the built-in ones of the same menu and name. The check here only guards the shape: balanced braces, popups with four items.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "content", "release", "menus.menu")
OUT = os.path.join(HERE, "..", "src", "menus_gen.h")
NL = chr(10)
BS = chr(92)


def check(text):
    plain = re.sub(r"//[^" + NL + "]*", "", text)
    if plain.count("{") != plain.count("}"):
        raise SystemExit("menus.menu: braces do not balance")
    for block in re.split(r"(?m)^menuDef", plain)[1:]:
        name = re.search(r'name\s+"([^"]+)"', block).group(1)
        items = len(re.findall(r"\bitemDef\b", block))
        if name != "main_text" and items != 4:
            raise SystemExit("menus.menu: popup %s has %d items, expected 4" % (name, items))


def build():
    text = open(SRC, encoding="utf-8", newline="").read().replace(chr(13) + NL, NL)
    check(text)
    out = ["// Generated by tools/gen_menus.py from content/release/menus.menu: do not edit.", "static const char built_in_menu[] ="]
    for line in text.split(NL):
        out.append('\t"' + line.replace(BS, BS + BS).replace('"', BS + '"') + BS + 'n"')
    out[-1] += ";"
    return (chr(13) + NL).join(out) + chr(13) + NL


def main():
    text = build()
    if "--check" in sys.argv:
        have = open(OUT, encoding="utf-8", newline="").read() if os.path.exists(OUT) else ""
        if have != text:
            print("src/menus_gen.h is out of date: run python -I tools/gen_menus.py")
            return 1
        print("menus_gen.h matches menus.menu")
        return 0
    with open(OUT, "w", encoding="utf-8", newline="") as f:
        f.write(text)
    print("wrote", os.path.normpath(OUT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
