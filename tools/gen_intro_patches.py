"""Write the patch of maps/_introscreen.gsc: a level's intro (the mission title on black, the
slam zoom) holds player 1 still and without weapons; in co-op it holds every player (QA buttons,
2026-10-21: player 2 walked and took a pistol while player 1 was held under the title).
Usage: python -I gen_intro_patches.py <extracted gsc root> <mod content/patches/maps dir>"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gsc_patch import Patch  # noqa: E402

gsc_root, out_dir = sys.argv[1], sys.argv[2]

CALLS = [
    ('level.player FreezeControls(', 'maps\\_mw2coop::players_freeze_controls('),
    ('level.player DisableWeapons()', 'maps\\_mw2coop::players_disable_weapons()'),
    ('level.player EnableWeapons()', 'maps\\_mw2coop::players_enable_weapons()'),
]

p = Patch(gsc_root, 'common/maps/_introscreen.gsc', out_dir)
p.note('''1. Every intro that holds player 1 still or takes his weapons away does it to every player
   (maps\\_mw2coop::players_freeze_controls, players_disable_weapons, players_enable_weapons;
   player 1 alone outside co-op).''')
names = re.findall(r'^(\w+)\([^)\n]*\)\s*$', p.src, re.M)
done = []
for name in names:
    for old, new in CALLS:
        if old in p.func(name):
            p.subst(name, old, new)
            done.append(name)
assert 'trainer_intro' in done and 'introscreen_delay' in done, done

p.note('''2. In co-op the intro plays on the mission's first start only, not again after a restart at a
   checkpoint or a campaign continued from one (both start the level at a start point): the
   game's own skip for other starts, dev-only code (/# #/), runs (maps\\_mw2coop::intro_skipped).''')
body = p.func('introscreen_delay')
dev = re.search(r'\t/#\n(\tskipIntro = !is_default_start\(\);\n\tif \( GetDebugDvar\( "introscreen" \) == "0" \)\n\t\tskipIntro = true;\n)', body)
assert dev, 'introscreen_delay: no dev-only intro skip'
p.replace(dev.group(0), '\tskipIntro = maps\\_mw2coop::intro_skipped();\n')
end = re.search(r'\t\treturn;\n\t\}\n\t#/\n', p.func('introscreen_delay'))
assert end, 'introscreen_delay: no end of the dev block'
p.replace(end.group(0), '\t\treturn;\n\t}\n')
p.write('_introscreen.gsc.patch', '''
mw2coop patch for maps/_introscreen.gsc (Modern Warfare 2, 64-bit Steam build). Generated by
tools/gen_intro_patches.py; do not edit by hand.''')
print('functions:', ' '.join(sorted(set(done))))
