"""Write the Takedown (favela) co-op patch, taking every replaced text from the extracted game
script so it matches byte for byte.
Usage: python -I gen_favela_patches.py <extracted gsc root> <mod content/patches/maps dir>"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gsc_patch import Patch  # noqa: E402

gsc_root, out_dir = sys.argv[1], sys.argv[2]
M = 'maps\\_mw2coop_favela::'

p = Patch(gsc_root, 'favela/maps/favela.gsc', out_dir)

p.note('''1. Opening car ride for every player: player 1 on the front passenger seat as before, player 2
   behind him on the back seat, each with his own rig (duck down, duck up, the death animation).''')
p.subst('opening_scene', 'thread player_rides_vehicle( player_vehicle );', M + 'players_ride( player_vehicle );')
p.subst('player_rides_vehicle', 'level.player', 'self')
p.subst('player_rides_vehicle', 'enablePlayerWeapons( false );', 'self DisableWeapons();')
body = p.func('player_rides_vehicle')
old = body[body.index('player_rig.origin = vehicle getTagOrigin'):body.index('player_rig linkTo( vehicle, "tag_passenger" );')] \
    + 'player_rig linkTo( vehicle, "tag_passenger" );'
p.subst('player_rides_vehicle', old, 'player_rig ' + M + 'place_rig( vehicle, self );')
p.subst('player_rides_vehicle', 'flag_set( "player_is_ducking" );', 'self ' + M + 'set_ducking( true );')
p.subst('player_rides_vehicle', 'flag_clear( "player_is_ducking" );', 'self ' + M + 'set_ducking( false );')
p.subst('player_rides_vehicle', 'notifyOnCommand(', 'self ' + M + 'notify_on_command(')
p.subst('player_dies_in_vehicle', 'level.player', 'self.mw2coop_player')

p.note('''2. Makarov's deadly shots through the windshield hit every player who is not ducking.''')
p.subst('makarov_shoot_player', 'if ( !flag( "player_is_ducking" ) )\n\t\t\t\tself thread kill_player();',
        M + 'deadly_shot();')
p.subst('kill_player', 'kill_player()', 'kill_player( player )')
p.subst('kill_player', 'level.player', 'player')
p.subst('kill_player', 'player notify( "shot_next_frame" );',
        'if ( !isdefined( player ) )\n\t\tplayer = level.player;\n\tplayer notify( "shot_next_frame" );')

p.note('''3. Getting out: player 1 as before; player 2 moves to the front seat once player 1 is out and
   gets out through the same open door, next to player 1.''')
p.subst('opening_scene', 'thread player_exits_vehicle( player_vehicle );', M + 'players_exit( player_vehicle );')
p.subst('player_exits_vehicle', 'level.player', 'self')
p.subst('player_exits_vehicle', 'enablePlayerWeapons( true );', 'self EnableWeapons();')
p.subst('player_exits_vehicle', 'exit_point = getent( "player_vehicle_exit_point", "targetname" );',
        'exit_point = self ' + M + 'exit_point();')
p.subst('player_exits_vehicle', 'dummy moveTo( exit_point.origin, MOVETIME, ACCEL, DECEL );',
        'self ' + M + 'via_front_seat( dummy, vehicle );\n\tdummy moveTo( exit_point.origin, MOVETIME, ACCEL, DECEL );')

p.write('favela.gsc.patch', '''
mw2coop patch for maps/favela.gsc (Takedown, Modern Warfare 2, 64-bit Steam build)
Generated by tools/gen_favela_patches.py from the game's own script; do not edit by hand.
Co-op logic lives in mw2coop/scripts/maps/_mw2coop_favela.gsc. Outside a co-op campaign session
every change does what the original did (the riding player is level.player there).
''')
