"""Write the co-op patches of the Gulag's evacuation (gulag_evac in gulag_ending.gsc, the notetrack in
gulag_ending_anim.gsc), taking every replaced text from the extracted game script so it matches byte
for byte. The logic lives in mw2coop/scripts/maps/_mw2coop_gulagend.gsc.
Usage: python -I gen_gulag_end_patches.py <extracted gsc root> <mod content/patches/maps dir>"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gsc_patch import Patch  # noqa: E402

gsc_root, out_dir = sys.argv[1], sys.argv[2]
M = 'maps\\_mw2coop_gulagend::'
TITLE = 'The Gulag, Modern Warfare 2, 64-bit Steam build'

p = Patch(gsc_root, 'gulag/maps/gulag_ending.gsc', out_dir)
p.note('''1. The evacuation (gulag_evac) for both players (maps\\_mw2coop_gulagend): player 2's rig, carabiner and
   extra rig play the same "evac", "hookup", "idle" and "fly_away" animations as player 1's; each player
   clips on by his own use of the rope's trigger (it stays on until both have); the black screens are on
   both screens. Before, player 2 stood in the rubble and the level ended without him.''')
p.replace('\tguys[ "player_rig" ] = player_rig;\n',
          '\tguys[ "player_rig" ] = player_rig;\n\tguys = ' + M + 'add_rig( guys );\n')
p.replace('\tblack_overlay.alpha = 1;\n\n\tif ( isdefined( level.black_overlay ) )\n',
          '\tblack_overlay.alpha = 1;\n\t' + M + 'partner_black( true, 0 );\n\n\tif ( isdefined( level.black_overlay ) )\n')
p.replace('\tblack_overlay FadeOverTime( 2 );\n\tblack_overlay.alpha = 0;\n',
          '\tblack_overlay FadeOverTime( 2 );\n\tblack_overlay.alpha = 0;\n\t' + M + 'partner_black( false, 2 );\n')
p.replace('\tlevel.player PlayerLinkToDelta( player_rig, "tag_player", 1, 0, 0, 0, 0, true );\n',
          '\tlevel.player PlayerLinkToDelta( player_rig, "tag_player", 1, 0, 0, 0, 0, true );\n\t' + M + 'partner_linked();\n')
p.replace('\tent delayThread( 20.16, ::anim_single_solo, extra_player_rig, "fly_away" );\n',
          '\tent delayThread( 20.16, ::anim_single_solo, extra_player_rig, "fly_away" );\n\t' + M + 'partner_extra( ent );\n')
p.replace('\tplayer_rig waittillmatch( "single anim", "end" );\n\tlevel.player Unlink();\n',
          '\tplayer_rig waittillmatch( "single anim", "end" );\n\tlevel.player Unlink();\n\t' + M + 'partner_free( ent );\n')
p.replace('\tflag_wait( "player_uses_rig" );\n\n\ttrigger trigger_off();\n',
          '\t' + M + 'use_wait( trigger, level.player );\n\n\t' + M + 'trigger_done( trigger );\n')
p.replace('\tblack_overlay.alpha = 1;\n\n\n\tnextmission();\n',
          '\tblack_overlay.alpha = 1;\n\t' + M + 'partner_black_out();\n\n\n\tnextmission();\n')
p.write('gulag_ending.gsc.patch', '''
mw2coop patch for maps/gulag_ending.gsc (''' + TITLE + '''). Generated by
tools/gen_gulag_end_patches.py; do not edit by hand. Co-op logic lives in mw2coop/scripts/maps/_mw2coop_gulagend.gsc.
''')

p = Patch(gsc_root, 'gulag/maps/gulag_ending_anim.gsc', out_dir)
p.note('''1. Soap's "player" notetrack: the cave-in buries a player who did not clip on in time; with two players
   it is whoever did not (maps\\_mw2coop_gulagend::all_hooked).''')
p.subst('got_player_notetrack', 'flag( "player_uses_rig" )', M + 'all_hooked()')
p.write('gulag_ending_anim.gsc.patch', '''
mw2coop patch for maps/gulag_ending_anim.gsc (''' + TITLE + '''). Generated by
tools/gen_gulag_end_patches.py; do not edit by hand.
''')
