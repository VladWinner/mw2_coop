"""Write the checkpoint hooks for start points marked only by a section handler: a function of
the level that the start point's start function threads and the level's normal flow calls when
the section before ends (found with tools/find_section_handlers.py, checked by hand). Its first
line becomes maps\\_mw2coop::section_reached( "<start point>" ). Each script gets a
<script>.cp.patch, applied by the DLL after the script's own patch (src/scripts.c).
Start points marked by a flag are in content/scripts/maps/_mw2coop_checkpoints.gsc.
Usage: python -I gen_checkpoint_patches.py <extracted gsc root> <mod content/patches/maps dir>"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gsc_patch import Patch  # noqa: E402

gsc_root, out_dir = sys.argv[1], sys.argv[2]

# level: [ (section handler, start point) ]
HANDLERS = {
    'invasion': [
        ('handler_yards_to_house_destroyer', 'yards'),
        ('handler_house_destroyer_to_pizza', 'bmp'),
        ('handler_gas_station_to_crash', 'gas_station'),
        ('handler_diner_defend', 'defend_diner'),
        ('handler_burgertown', 'burgertown'),
        ('handler_convoy', 'convoy'),
    ],
    'oilrig': [('AA_heli_init', 'heli')],
    'favela_escape': [('market_evac_escape', 'market_evac_escape'), ('roofrun', 'roofrun')],
    'dcburning': [('AA_heli_ride2', 'heliride2')],
    'contingency': [('handle_woods', 'woods'), ('handle_ridge', 'ridge')],
}


def script_of(level, function):
    d = os.path.join(gsc_root, level, 'maps')
    hits = []
    for f in sorted(os.listdir(d)):
        if f.endswith('.gsc'):
            text = open(os.path.join(d, f), encoding='latin-1').read().replace('\r', '')
            if '\n' + function + '(' in '\n' + text or '\n' + function + ' (' in '\n' + text:
                hits.append(f)
    assert len(hits) == 1, (level, function, hits)
    return hits[0]


for level, pairs in HANDLERS.items():
    by_script = {}
    for function, start in pairs:
        by_script.setdefault(script_of(level, function), []).append((function, start))
    for script, items in by_script.items():
        p = Patch(gsc_root, level + '/maps/' + script, out_dir)
        for n, (function, start) in enumerate(items, 1):
            body = p.func(function)
            header = '\n' + body[:body.index('{') + 1] + '\n'	# from the line start: a name may end another
            p.note('''{0}. "{1}" is reached when its section handler {2}() begins (the section before
   calls it): the co-op checkpoint (maps\\_mw2coop::section_reached).'''.format(n, start, function))
            p.replace(header, header + '\tmaps\\_mw2coop::section_reached( "' + start + '" );\n')
        p.write(script + '.cp.patch', '''
mw2coop checkpoint hooks for maps/{0} (Modern Warfare 2, 64-bit Steam build), applied after
the script's own patch. Generated by tools/gen_checkpoint_patches.py; do not edit by hand.'''.format(script))
