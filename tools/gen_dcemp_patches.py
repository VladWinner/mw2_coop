"""Write the crash site (dc_crashsite, shared by dcburning and dcemp) and Second Sun (dcemp)
co-op patches, taking every replaced text from the extracted game scripts so it matches byte for
byte.
Usage: python -I gen_dcemp_patches.py <extracted gsc root> <mod content/patches/maps dir>"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gsc_patch import Patch  # noqa: E402

gsc_root, out_dir = sys.argv[1], sys.argv[2]
C = 'maps\\_mw2coop_crashsite::'
D = 'maps\\_mw2coop_dcemp::'
ALL = 'foreach ( p in ' + C + 'crash_players() )\n\t\tp '

# ---------------------------------------------------------------- dc_crashsite.gsc (both zones)
p = Patch(gsc_root, 'dcemp/maps/dc_crashsite.gsc', out_dir)
p.note('''1. Player 2 wakes up in the wreck beside player 1 with his own rig and the same animation,
   and moves inside the cabin on his own (player_crash_movement on the player it runs for).''')
p.subst('AAA_sequence_player_crash_site', 'level.player enableinvulnerability();', ALL + 'enableinvulnerability();')
p.subst('AAA_sequence_player_crash_site', 'crash_node anim_first_frame( anim_actors_rescue, "dcburning_BHrescue" );',
        'crash_node anim_first_frame( anim_actors_rescue, "dcburning_BHrescue" );\n\t' + C + 'partner_rig_setup( crash_node, ePlayer_rig );')
p.subst('AAA_sequence_player_crash_site',
        'thread player_crash_movement(  movement_grid[ "top_left" ], movement_grid[ "bot_right" ], ePlayer_rig );',
        'level.player thread player_crash_movement(  movement_grid[ "top_left" ], movement_grid[ "bot_right" ], ePlayer_rig );')
p.subst('AAA_sequence_player_crash_site', 'crash_node thread anim_single( anim_actors_rescue, "dcburning_BHrescue" );',
        'crash_node thread anim_single( anim_actors_rescue, "dcburning_BHrescue" );\n\t' + C + 'partner_rig_play();')
p.subst('AAA_sequence_player_crash_site', 'level.player.ignoreme = true;',
        'foreach ( p in ' + C + 'crash_players() )\n\t\tp.ignoreme = true;')
p.subst('player_crash_movement', 'level.player', 'self')
p.subst('open_player_fov', 'level.player', 'self')
p.note('''2. Every player gets his rifle and Foley's magazine.''')
p.subst('AA_crash_site_init', 'thread player_crash_gun_behavior();', C + 'gun_behavior();')
p.subst('player_crash_gun_behavior', 'level.player', 'self')
p.subst('player_crash_gun_behavior', 'thread autosave_now( true );',
        'if ( self == level.player )\n\t\tthread autosave_now( true );')
p.note('''3. Every player loses the crash site's invulnerability at the white-out.''')
p.subst('crash_end_scene', 'level.player disableinvulnerability();', ALL + 'disableinvulnerability();')
p.write('dc_crashsite.gsc.patch', '''
mw2coop patch for maps/dc_crashsite.gsc (Black Hawk crash site, the same script in the dcburning
and dcemp zones; Modern Warfare 2, 64-bit Steam build). Generated by tools/gen_dcemp_patches.py;
do not edit by hand. Co-op logic lives in mw2coop/scripts/maps/_mw2coop_crashsite.gsc. Outside a
co-op campaign session every change does what the original did (the player is level.player).
''')

# ---------------------------------------------------------------- dcemp.gsc
d = Patch(gsc_root, 'dcemp/maps/dcemp.gsc', out_dir)
d.note('''1. Start points that set up the crash site run its movement on player 1.''')
for fn in ('start_iss', 'start_emp'):
    d.subst(fn, 'thread maps\\dc_crashsite::player_crash_movement(', 'level.player thread maps\\dc_crashsite::player_crash_movement(')
d.note('''2. ISS: player 2's view is kept for after the EMP; both players' view limits follow the scene.''')
d.subst('iss_main', 'level.emp_player_stance = level.player getstance();',
        'level.emp_player_stance = level.player getstance();\n\t' + D + 'save_partner_view();')
d.subst('iss_temp_satelite_anim', 'level.player lerpViewAngleClamp(', 'foreach ( p in level.players )\n\t\tp lerpViewAngleClamp(')
d.subst('iss_temp_satelite_anim', 'level.player freezecontrols( false );', 'foreach ( p in level.players )\n\t\tp freezecontrols( false );')
d.note('''3. After the white-out every player is back in his own place in the wreck, and both are let out.''')
d.subst('emp_main', 'thread emp_empaftermath();', D + 'players_empaftermath();')
d.subst('emp_empaftermath', 'level.player', 'self')
d.subst('emp_empaftermath', 'level.emp_player_angles', 'self ' + D + 'emp_angles()')
d.subst('emp_empaftermath', 'level.emp_player_stance', 'self ' + D + 'emp_stance()')
d.subst('emp_marine1', 'delaythread( 5.5, ::emp_free_player );', 'delaythread( 5.5, ' + D + 'players_free );')
d.subst('emp_free_player', 'level.player', 'self')
d.subst('emp_free_player', 'crash_site_clip delete();', 'if ( isdefined( crash_site_clip ) )\n\t\tcrash_site_clip delete();')
d.subst('emp_free_player', 'rig moveto( end.origin, time, time * .5, time * .5 );',
        'rig moveto( self ' + D + 'free_exit_origin( end ), time, time * .5, time * .5 );')
d.write('dcemp.gsc.patch', '''
mw2coop patch for maps/dcemp.gsc (Second Sun, Modern Warfare 2, 64-bit Steam build)
Generated by tools/gen_dcemp_patches.py from the game's own script; do not edit by hand.
Co-op logic lives in mw2coop/scripts/maps/_mw2coop_dcemp.gsc. Outside a co-op campaign session
every change does what the original did (the player is level.player there).
''')

# ---------------------------------------------------------------- dcemp_code.gsc
c = Patch(gsc_root, 'dcemp/maps/dcemp_code.gsc', out_dir)
c.note('''1. ISS: player 2 floats beside player 1.''')
c.subst('iss_camera_setup', 'level.player PlayerSetGroundReferenceEnt( camera );',
        'level.player PlayerSetGroundReferenceEnt( camera );\n\t' + D + 'partner_iss_camera( camera );')
c.write('dcemp_code.gsc.patch', '''
mw2coop patch for maps/dcemp_code.gsc (Second Sun, Modern Warfare 2, 64-bit Steam build)
Generated by tools/gen_dcemp_patches.py from the game's own script; do not edit by hand.
Co-op logic lives in mw2coop/scripts/maps/_mw2coop_dcemp.gsc.
''')
