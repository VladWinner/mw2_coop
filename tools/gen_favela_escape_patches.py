"""Write the Escape from Favela (favela_escape) co-op patch of maps/favela_escape.gsc (the chopper
ladder's own patch is in favela_escape_code.gsc.patch, written by gen_seek_patches.py), taking every
replaced text from the extracted game script so it matches byte for byte.
Usage: python -I gen_favela_escape_patches.py <extracted gsc root> <mod content/patches/maps dir>"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gsc_patch import Patch  # noqa: E402

gsc_root, out_dir = sys.argv[1], sys.argv[2]
M = 'maps\\_mw2coop_favelaescape::'

p = Patch(gsc_root, 'favela_escape/maps/favela_escape.gsc', out_dir)

p.note('''1. The end of the mission: player 2's screen fades to black with player 1's, as the level fades
   level.player's (the chopper flies off with both on the rope ladder, see favela_escape_code.gsc.patch).''')
p.replace('\tblack_overlay.alpha = 1;\n', '\tblack_overlay.alpha = 1;\n\t' + M + 'partner_black( fadeTime );\n')

p.write('favela_escape.gsc.patch', '''
mw2coop patch for maps/favela_escape.gsc (Escape from Favela, Modern Warfare 2, 64-bit Steam build). Generated by
tools/gen_favela_escape_patches.py; do not edit by hand.
''')
